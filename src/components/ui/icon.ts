function normalizeSvg(svg: string): string {
  return svg
    .replace(/width="[^"]*"/, 'width="1em"')
    .replace(/height="[^"]*"/, 'height="1em"')
    .replace('<svg ', '<svg fill="currentColor" aria-hidden="true" focusable="false" ');
}

export function icon(name: IconName, className = ''): string {
  const svg = normalizeSvg(ICON_SVGS[name]);
  return `<span class="icon ${className}" aria-hidden="true">${svg}</span>`;
}
